"""Regenerate the original contact-wire mesh/buffer; never reads native binaries.

A 1 m long square tube along +x, centred on y=0,z=0, rendered with the native tram
cable material by content/tram_wire.mdl. All counts/offsets in the .msh are bytes.
"""
from pathlib import Path
import struct
r=Path(__file__).resolve().parents[1]
h=0.008  # half thickness: 1.6 cm tube
pos=[];uv=[];norm=[];tang=[];indices=[]
# Each side face as (normal, edge a (y,z), edge b (y,z)); a->b turns positively around +x.
faces=[((0,0,1),(-h,h),(h,h)),((0,1,0),(h,h),(h,-h)),((0,0,-1),(h,-h),(-h,-h)),((0,-1,0),(-h,-h),(-h,h))]
for normal,(y0,z0),(y1,z1) in faces:
 base=len(pos)
 pos+=[(0,y0,z0),(1,y0,z0),(1,y1,z1),(0,y1,z1)]
 uv+=[(0,0),(1,0),(1,1),(0,1)]
 norm+=[normal]*4
 tang+=[(1,0,0,1)]*4
 indices+=[base,base+1,base+2,base,base+2,base+3]
blob=b''.join(struct.pack('<3f',*p) for p in pos)+b''.join(struct.pack('<2f',*p) for p in uv)+b''.join(struct.pack('<3f',*p) for p in norm)+b''.join(struct.pack('<4f',*p) for p in tang)
offsets={}
o=0
for name,n,comp in (('position',len(pos),3),('uv0',len(uv),2),('normal',len(norm),3),('tangent',len(tang),4)):
 offsets[name]=(n*comp*4,comp,o);o+=n*comp*4
idx=len(indices)*4
blob+=struct.pack('<%dI'%len(indices),*indices)*4
(r/'content/tram_wire.msh.blob').write_bytes(blob)
va=','.join('%s={count=%d,numComp=%d,offset=%d}'%(k,*offsets[k]) for k in offsets)
ix=','.join('%s={count=%d,offset=%d}'%(k,idx,o+i*idx) for i,k in enumerate(offsets))
(r/'content/tram_wire.msh').write_text('''-- Original contact wire: 1 m long 1.6 cm square tube along +x. All counts/offsets are bytes.
-- Generated by scripts/generate_tram_wire_mesh.py; rendered with the native tram cable material.
function data()
 return {subMeshes={{indices={%s}}},
  vertexAttr={%s}}
end
'''%(ix,va),encoding='utf-8',newline='\n')
